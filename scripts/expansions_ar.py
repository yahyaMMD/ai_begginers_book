def inject(num: str, body: str) -> str:
    extra = EXPANSIONS.get(str(num), "")
    if not extra:
        return body
    for marker in ('<div class="takeaway">', '<div class="action-steps">'):
        idx = body.find(marker)
        if idx != -1:
            return body[:idx] + extra + body[idx:]
    return body + extra
